import * as React from "react"
import { cn } from "@/lib/utils"

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { variant?: "default" | "elevated" | "bordered" | "interactive" }
>(({ className, variant = "default", children, ...props }, ref) => {
  const variants = {
    default: "bg-bg-elevated rounded-xl border border-border",
    elevated: "bg-bg-elevated rounded-xl shadow-md",
    bordered: "bg-bg-elevated rounded-xl border border-border-strong",
    interactive: "bg-bg-elevated rounded-xl border border-border interactive",
  }

  return (
    <div
      ref={ref}
      className={cn(variants[variant], className)}
      {...props}
    >
      {children}
    </div>
  )
})
Card.displayName = "Card"

